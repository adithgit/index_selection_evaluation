"""Wu et al. calibration for pg_lab PG18 (port 5433) -- PHASE 2 (cold I/O).
Run IMMEDIATELY after:
  pg_ctl -D /Users/adithyaudayan/pg_lab/pg-build/pg-18/data restart
  sudo -n /usr/sbin/purge
Emits calibration/pglab/postgres_cost_units_pglab.json.
"""
import psycopg2, json, time, os, datetime
HERE = os.path.dirname(os.path.abspath(__file__))
PORT = 5433
p=json.load(open(os.path.join(HERE,"_partial_pglab.json")))
ct,ci,co=p['ct'],p['ci'],p['co']
Ps,Ts=p['r_seq']['P'],p['r_seq']['T']; Pr,Tr=p['r_rand']['P'],p['r_rand']['T']

conn=None
for _ in range(30):
    try: conn=psycopg2.connect(dbname="pgcalib",port=PORT); conn.autocommit=True; break
    except Exception: time.sleep(1)
if conn is None: raise SystemExit("could not connect to pgcalib on 5433 (is pg_lab back up?)")

def ex(s):
    with conn.cursor() as c: c.execute(s)
def ea(sql, fi=False):
    ex("set max_parallel_workers_per_gather=0"); ex("set jit=off")
    ex(f"set enable_seqscan={'off' if fi else 'on'}"); ex(f"set enable_bitmapscan={'off' if fi else 'on'}")
    with conn.cursor() as c:
        c.execute("explain (analyze,buffers,timing on,format json) "+sql); pl=c.fetchone()[0][0]
    hit=[0]; read=[0]; rows=[pl["Plan"].get("Actual Rows",0)]
    def w(n):
        hit[0]+=n.get("Shared Hit Blocks",0); read[0]+=n.get("Shared Read Blocks",0)
        for ch in n.get("Plans",[]): w(ch)
    w(pl["Plan"])
    return pl["Execution Time"], hit[0], read[0], rows[0]

print("=== COLD I/O probes on pg_lab ===")
t4,hit4,read4,_ = ea("select * from r_seq")
print(f"q4 seq scan r_seq : {t4:8.1f}ms  read_blocks={read4}  hit_blocks={hit4}  "
      f"({'COLD ok' if read4>0.8*Ps else 'WARM! cache not cleared'})")
cs=(t4 - ct*Ts)/read4 if read4 else float('nan')

t5,hit5,read5,m5 = ea("select * from r_rand where a between 1 and 30000", fi=True)
print(f"q5 idx scan r_rand: {t5:8.1f}ms  read_blocks={read5}  hit_blocks={hit5}  matched={m5}  "
      f"({'COLD ok' if read5>0.5*m5 else 'WARM! cache not cleared'})")
cr=(t5 - (ct+ci+co)*m5)/read5 if read5 else float('nan')

units={"seq_page_cost":cs,"random_page_cost":cr,"cpu_tuple_cost":ct,
       "cpu_index_tuple_cost":ci,"cpu_operator_cost":co}
print("\n=== calibrated cost units (absolute, ms/op) ===")
for k,v in units.items(): print(f"  {k:22s} {v:.6g}")
norm={k:round(v/cs,5) for k,v in units.items()}
print("\n=== normalized to seq_page_cost=1.0 ===")
for k,v in norm.items(): print(f"  {k:22s} {v:.5f}")
out={"_comment":"pg_lab PG18 instance (port 5433). Generated by calibrate_pglab_2_io_cold.py",
     "protocol":"cpu-warm / io-cold (Wu et al. ICDE 2013)",
     "calibrated_on":datetime.date.today().isoformat(),
     "gucs":norm,"absolute_ms_per_op":units,"read_blocks":{"q4":read4,"q5":read5}}
json.dump(out, open(os.path.join(HERE,"postgres_cost_units_pglab.json"),"w"),indent=2)
print("\nsaved calibration/pglab/postgres_cost_units_pglab.json")
conn.close()
a=psycopg2.connect(dbname="postgres",port=PORT); a.autocommit=True
with a.cursor() as c: c.execute("drop database if exists pgcalib")
a.close(); print("dropped pgcalib")
